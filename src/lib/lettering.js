const JIT = [-4, 3, -2, 4, -3, 2, -1, 3, -2];

export function lettering(text) {
  const S = 26, gap = 14, segs = [], eyes = [];
  let x = 0, i = 0;
  for (const raw of text.toUpperCase()) {
    if (raw === ' ' || raw === '-') { x += 34; continue; }
    const g = G[raw];
    if (!g) continue;
    const a = (JIT[i % JIT.length] * Math.PI) / 180, cx = x + g.w / 2, dy = i % 2 ? 3 : -3;
    const first = segs.length;
    for (const pl of g.s) {
      segs.push(pl.map(([px, py]) => {
        const rx = x + px - cx, ry = py - 50;
        return [cx + rx * Math.cos(a) - ry * Math.sin(a), 50 + dy + rx * Math.sin(a) + ry * Math.cos(a)];
      }));
    }
    if (i % 4 === 1) {
      const [p0, p1] = segs[first];
      for (const f of [0.32, 0.68]) eyes.push([p0[0] + (p1[0] - p0[0]) * f, p0[1] + (p1[1] - p0[1]) * f]);
    }
    x += g.w + S + gap;
    i++;
  }
  const W = x - S - gap, pad = 30;
  const d = segs.map((pl) => 'M' + pl.map(([px, py]) => `${px.toFixed(1)} ${py.toFixed(1)}`).join(' L')).join(' ');
  const eyesD = eyes.map(([ex, ey]) => `M${(ex - 4.5).toFixed(1)} ${ey.toFixed(1)} a4.5 4.5 0 1 0 9 0 a4.5 4.5 0 1 0 -9 0`).join(' ');
  return { d, eyes: eyesD, viewBox: `${-pad} ${-pad} ${W + pad * 2} ${100 + pad * 2}`, ratio: (W + pad * 2) / (100 + pad * 2) };
}
